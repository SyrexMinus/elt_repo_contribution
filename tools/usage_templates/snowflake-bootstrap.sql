USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS ${SNOWFLAKE_PREFIX}_BOOTSTRAP;
CREATE NETWORK POLICY IF NOT EXISTS ${SNOWFLAKE_PREFIX}_OPERATOR_IP;
ALTER NETWORK POLICY ${SNOWFLAKE_PREFIX}_OPERATOR_IP
  SET ALLOWED_IP_LIST = ('$OPERATOR_PUBLIC_IP/32');

CREATE USER IF NOT EXISTS $SNOWFLAKE_TERRAFORM_USER
  TYPE = SERVICE
  DEFAULT_ROLE = 'ACCOUNTADMIN';
GRANT ROLE ACCOUNTADMIN TO USER $SNOWFLAKE_TERRAFORM_USER;
ALTER USER $SNOWFLAKE_TERRAFORM_USER
  SET RSA_PUBLIC_KEY = '$TF_RSA_PUBLIC_KEY'
  NETWORK_POLICY = ${SNOWFLAKE_PREFIX}_OPERATOR_IP;

CREATE ROLE IF NOT EXISTS $SNOWFLAKE_RUNTIME_ROLE;
GRANT ROLE $SNOWFLAKE_RUNTIME_ROLE TO ROLE SYSADMIN;
CREATE USER IF NOT EXISTS $SNOWFLAKE_RUNTIME_USER
  TYPE = SERVICE
  DEFAULT_ROLE = '$SNOWFLAKE_RUNTIME_ROLE'
  NETWORK_POLICY = ${SNOWFLAKE_PREFIX}_OPERATOR_IP;
GRANT ROLE $SNOWFLAKE_RUNTIME_ROLE TO USER $SNOWFLAKE_RUNTIME_USER;

CREATE AUTHENTICATION POLICY IF NOT EXISTS ${SNOWFLAKE_PREFIX}_BOOTSTRAP.PUBLIC.PIPELINE_PAT
  AUTHENTICATION_METHODS = ('ALL')
  PAT_POLICY = (
    DEFAULT_EXPIRY_IN_DAYS = 365
    MAX_EXPIRY_IN_DAYS = 365
    NETWORK_POLICY_EVALUATION = ENFORCED_REQUIRED
  );
ALTER USER $SNOWFLAKE_RUNTIME_USER
  SET AUTHENTICATION POLICY ${SNOWFLAKE_PREFIX}_BOOTSTRAP.PUBLIC.PIPELINE_PAT;
ALTER USER $SNOWFLAKE_RUNTIME_USER
  ADD PROGRAMMATIC ACCESS TOKEN IF NOT EXISTS ELT_PIPELINE_365
  ROLE_RESTRICTION = '$SNOWFLAKE_RUNTIME_ROLE'
  DAYS_TO_EXPIRY = 365;
