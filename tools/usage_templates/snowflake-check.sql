USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ${SNOWFLAKE_PREFIX}_WH;
USE DATABASE ${SNOWFLAKE_PREFIX}_DB;

SELECT 'SILVER.PULL' AS relation, COUNT(*) AS row_count FROM SILVER.PULL
UNION ALL SELECT 'SILVER.FILE', COUNT(*) FROM SILVER.FILE
UNION ALL SELECT 'SILVER.REVIEW', COUNT(*) FROM SILVER.REVIEW
UNION ALL SELECT 'GOLD.FACT_TIME_TO_SHIP', COUNT(*) FROM GOLD.FACT_TIME_TO_SHIP
UNION ALL SELECT 'GOLD.FACT_PR_DIRECTORY', COUNT(*) FROM GOLD.FACT_PR_DIRECTORY
UNION ALL SELECT 'GOLD.FACT_REVIEW_INTERACTIONS', COUNT(*) FROM GOLD.FACT_REVIEW_INTERACTIONS;

SELECT REPO, COUNT(*) AS row_count
FROM SILVER.PULL
WHERE REPO IN ('apache/spark', 'ClickHouse/ClickHouse')
GROUP BY REPO;
